"""Build and push a private Kaggle CPU kernel that runs a list of train_gbdt.py jobs, then fetch its runs.

Kaggle script kernels are one file, so the kernel embeds every module in src/ as text, writes them to
/kaggle/working/src and runs each job in a subprocess. Outputs land in /kaggle/working/runs/<name>/.

Usage (from the repo root):
  .venv/bin/python scripts/kaggle_kernel.py push  --kernel lgb1 --jobs jobs/lgb1.txt
  .venv/bin/python scripts/kaggle_kernel.py status --kernel lgb1
  .venv/bin/python scripts/kaggle_kernel.py fetch  --kernel lgb1

A jobs file has one argument string per line for train_gbdt.py, or a line starting with another script
name (e.g. `train_fintfm.py --strategy balanced ...`), or `pip install PKG` (needs --internet); blank lines
and # comments are ignored.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
USER = "muhakabartay"
ORIGINAL = "uditjain13/credit-card-fraud-detection-2026"
COMPETITION = "playground-series-s6e11"

TEMPLATE = '''"""Auto-generated by scripts/kaggle_kernel.py (playground-series-s6e11). Do not edit."""
import os, subprocess, sys, time
from pathlib import Path

SRC = {src!r}
JOBS = {jobs!r}

d = Path("/kaggle/working/src"); d.mkdir(parents=True, exist_ok=True)
for name, text in SRC.items():
    (d / name).write_text(text)
env = dict(os.environ, S6E11_THREADS="4")
for j, args in enumerate(JOBS):
    t0 = time.time()
    print(f"=== job {{j + 1}}/{{len(JOBS)}}: {{args}}", flush=True)
    argv = args.split()
    if argv[0] == "pip":
        r = subprocess.run([sys.executable, "-m", "pip", "install", "-q", *argv[2:]])
        print(f"=== exit {{r.returncode}} after {{time.time() - t0:.0f}}s", flush=True)
        continue
    script = argv.pop(0) if argv[0].endswith(".py") else "train_gbdt.py"
    r = subprocess.run([sys.executable, script, *argv], cwd=d, env=env)
    print(f"=== exit {{r.returncode}} after {{time.time() - t0:.0f}}s", flush=True)
'''


def slug(kernel: str) -> str:
    """Kaggle kernel slug for a short kernel name."""
    return f"s6e11-{kernel}"


def build(kernel: str, jobs: list[str], out: Path, internet: bool = False, gpu: bool = False) -> None:
    """Write run.py and kernel-metadata.json for one kernel into `out` (gpu: T4 x2, uses weekly GPU quota)."""
    src = {p.name: p.read_text() for p in sorted((ROOT / "src").glob("*.py"))}
    (out / "run.py").write_text(TEMPLATE.format(src=src, jobs=jobs))
    meta = {
        "id": f"{USER}/{slug(kernel)}",
        "title": slug(kernel),
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",
        "enable_gpu": "true" if gpu else "false",
        "enable_tpu": "false",
        "enable_internet": "true" if internet else "false",
        "dataset_sources": [ORIGINAL],
        "competition_sources": [COMPETITION],
        "kernel_sources": [],
        "model_sources": [],
    }
    if gpu:
        meta["machine_shape"] = "NvidiaTeslaT4"
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))


def read_jobs(path: Path) -> list[str]:
    """Parse a jobs file: one argument string per line, # comments allowed.

    Raises:
        FileNotFoundError: the file does not exist.
        ValueError: the file holds no job.
    """
    lines = [ln.split("#", 1)[0].strip() for ln in path.read_text().splitlines()]
    jobs = [ln for ln in lines if ln]
    if not jobs:
        raise ValueError(f"{path} holds no job")
    return jobs


def fetch(kernel: str) -> None:
    """Download a kernel's output and copy its run directories into runs/, printing each run's CV."""
    with tempfile.TemporaryDirectory() as t:
        subprocess.run(["kaggle", "kernels", "output", f"{USER}/{slug(kernel)}", "-p", t, "-o"], check=True)
        runs = ROOT / "runs"
        # Run dirs with meta.json, plus train_lm.py dirs holding only per-fold files (kernel cut short).
        dirs = {p.parent for p in Path(t).rglob("meta.json")} | {p.parent for p in Path(t).rglob("fold*.npz")}
        for src in sorted(dirs):
            dst = runs / src.name
            if dst.exists():
                shutil.rmtree(dst)
            shutil.copytree(src, dst)
            meta = src / "meta.json"
            if not meta.exists():
                done = sorted(p.name for p in src.glob("fold*.npz"))
                print(f"{src.name}: no meta.json, fold files {done}")
                continue
            m = json.loads(meta.read_text())
            print(f"{src.name}: CV {m['cv']:.5f} folds {[round(x, 5) for x in m['folds']]}")
        logs = sorted(Path(t).glob("*.log"))
        if logs:
            shutil.copy(logs[0], runs / f"kernel_{kernel}.log")


def main(argv: list[str] | None = None) -> int:
    """Push, check or fetch one kernel; return the exit status."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("action", choices=["push", "status", "fetch"])
    ap.add_argument("--kernel", required=True)
    ap.add_argument("--jobs", type=Path)
    ap.add_argument("--internet", action="store_true", help="needed by train_fintfm.py (pip + checkpoint)")
    ap.add_argument(
        "--gpu",
        action="store_true",
        help="T4 x2 GPU kernel: uses the weekly Kaggle GPU quota; state a time estimate first (CLAUDE.md)",
    )
    a = ap.parse_args(argv)
    if a.action == "push" and a.jobs is None:
        ap.error("push needs --jobs")
    try:
        if a.action == "push":
            jobs = read_jobs(a.jobs)
            with tempfile.TemporaryDirectory() as t:
                build(a.kernel, jobs, Path(t), a.internet, a.gpu)
                subprocess.run(["kaggle", "kernels", "push", "-p", t], check=True)
        elif a.action == "status":
            subprocess.run(["kaggle", "kernels", "status", f"{USER}/{slug(a.kernel)}"], check=True)
        else:
            fetch(a.kernel)
    except (OSError, ValueError) as e:
        print(f"kaggle_kernel.py: error: {e}", file=sys.stderr)
        return 2
    except subprocess.CalledProcessError as e:
        print(f"kaggle_kernel.py: {' '.join(e.cmd[:3])} exited {e.returncode}", file=sys.stderr)
        return e.returncode
    return 0


if __name__ == "__main__":
    sys.exit(main())
